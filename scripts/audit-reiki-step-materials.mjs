import { mkdir, readFile, writeFile } from "node:fs/promises";
import { Buffer } from "node:buffer";

const knowledgeSourcePath = new URL("../src/data/reikiKnowledgeBase.js", import.meta.url);
const settingsSourcePath = new URL("../src/data/reikiStepSettings.js", import.meta.url);
const docsDir = new URL("../docs/", import.meta.url);
const jsonReportPath = new URL("../docs/reiki-step-materials-coverage.json", import.meta.url);
const mdReportPath = new URL("../docs/reiki-step-materials-coverage.md", import.meta.url);

const EXPECTED_TOTAL_LEVELS = 7;
const EXPECTED_TOTAL_STEPS = 37;

function dataModuleUrl(source) {
  return `data:text/javascript;base64,${Buffer.from(source).toString("base64")}`;
}

function extractCustomDraftIds(source) {
  const draftsMatch = source.match(/const\s+STEP_DRAFTS\s*=\s*\{([\s\S]*?)\n\};/);
  if (!draftsMatch) return new Set();

  return new Set([...draftsMatch[1].matchAll(/"(RY-L\d{2}-S\d{2})"\s*:/g)].map((match) => match[1]));
}

function missingContentFields(step) {
  const missing = [];
  for (const field of ["intro", "meaning", "result"]) {
    if (!step[field] || step[field] === "needs_content" || step[field] === "needs verification") missing.push(field);
  }
  for (const field of ["opens", "skills"]) {
    if (!Array.isArray(step[field]) || step[field].length === 0) missing.push(field);
  }
  return missing;
}

function readiness(step, hasCustomDraftContent, hasSourcedSettings, missingFields) {
  if (step.contentStatus === "content_verified" && hasSourcedSettings && missingFields.length === 0) {
    return "ready_for_public_learner_ui";
  }

  if (hasCustomDraftContent && hasSourcedSettings && missingFields.length === 0) {
    return "draft_public_copy_needs_author_review";
  }

  if (!hasCustomDraftContent && hasSourcedSettings && missingFields.length === 0) {
    return "generated_draft_needs_author_content";
  }

  return "not_ready_needs_content_or_settings";
}

function groupByLevel(rows) {
  return rows.reduce((groups, row) => {
    const key = String(row.levelId);
    groups[key] ??= [];
    groups[key].push(row);
    return groups;
  }, {});
}

function markdownTable(rows) {
  const lines = [
    "| ID | Ступень | Материал | Настройки | Статус |",
    "|---|---|---|---:|---|"
  ];

  for (const row of rows) {
    const material = row.hasCustomDraftContent ? "custom draft" : "generated draft";
    const settings = row.hasSourcedSettings ? String(row.settingsCount) : "0";
    lines.push(`| ${row.id} | ${row.title} | ${material} | ${settings} | ${row.readiness} |`);
  }

  return lines.join("\n");
}

function buildMarkdown(report) {
  const grouped = groupByLevel(report.steps);
  const sections = Object.entries(grouped)
    .map(([levelId, rows]) => {
      const level = report.levels.find((item) => String(item.id) === levelId);
      return `## Уровень ${levelId}. ${level?.name ?? "needs verification"}\n\n${markdownTable(rows)}`;
    })
    .join("\n\n");

  return `# Reiki Yggdrasil — step materials coverage\n\nGenerated by \`npm run audit:reiki-materials\`.\n\n## Summary\n\n- Total levels: ${report.summary.totalLevels}\n- Total steps: ${report.summary.totalSteps}\n- Steps with custom draft content: ${report.summary.stepsWithCustomDraftContent}\n- Steps with generated draft only: ${report.summary.stepsWithGeneratedDraftOnly}\n- Steps with sourced settings: ${report.summary.stepsWithSourcedSettings}\n- Steps missing sourced settings: ${report.summary.stepsMissingSourcedSettings}\n- Public-ready verified steps: ${report.summary.publicReadyVerifiedSteps}\n\n## Interpretation\n\n- \`custom draft\` means the step has an explicit entry in \`STEP_DRAFTS\`.\n- \`generated draft\` means learner-facing copy is generated from the step title/theme and still needs author methodichka review.\n- \`sourced settings\` means the step has explicit settings in \`sourcedStepSettings\`.\n- No step should be treated as final author-verified material unless its content status is explicitly upgraded to \`content_verified\`.\n\n## Missing sourced settings\n\n${report.missingSourcedSettings.length ? report.missingSourcedSettings.map((row) => `- ${row.id} — ${row.title}`).join("\n") : "None."}\n\n${sections}\n\n## Risks\n\n- Course structure is present, but generated drafts are not equivalent to final author methodichka materials.\n- Settings can be present while central descriptions still need author review.\n- UI should continue to show RU-default copy and avoid claiming final verification until the statuses are updated.\n`;
}

const [knowledgeSource, settingsSource] = await Promise.all([
  readFile(knowledgeSourcePath, "utf8"),
  readFile(settingsSourcePath, "utf8")
]);

const [{ reikiKnowledgeMeta, reikiLevels, reikiSteps }, { sourcedStepSettings }] = await Promise.all([
  import(dataModuleUrl(knowledgeSource)),
  import(dataModuleUrl(settingsSource))
]);

const customDraftIds = extractCustomDraftIds(knowledgeSource);
const errors = [];

if (reikiKnowledgeMeta.totalLevels !== EXPECTED_TOTAL_LEVELS) {
  errors.push(`Expected ${EXPECTED_TOTAL_LEVELS} levels, found ${reikiKnowledgeMeta.totalLevels}.`);
}

if (reikiKnowledgeMeta.totalSteps !== EXPECTED_TOTAL_STEPS) {
  errors.push(`Expected ${EXPECTED_TOTAL_STEPS} steps, found ${reikiKnowledgeMeta.totalSteps}.`);
}

const steps = reikiSteps.map((step) => {
  const settings = sourcedStepSettings[step.id] ?? [];
  const hasCustomDraftContent = customDraftIds.has(step.id);
  const hasSourcedSettings = Array.isArray(settings) && settings.length > 0;
  const missingFields = missingContentFields(step);

  return {
    id: step.id,
    levelId: step.levelId,
    number: step.number,
    label: step.label,
    title: step.title,
    contentStatus: step.contentStatus,
    hasCustomDraftContent,
    hasGeneratedDraftContent: !hasCustomDraftContent,
    hasSourcedSettings,
    settingsCount: hasSourcedSettings ? settings.length : 0,
    missingFields,
    readiness: readiness(step, hasCustomDraftContent, hasSourcedSettings, missingFields)
  };
});

const missingSourcedSettings = steps.filter((step) => !step.hasSourcedSettings);
const stepsWithGeneratedDraftOnly = steps.filter((step) => step.hasGeneratedDraftContent);
const stepsWithCustomDraftContent = steps.filter((step) => step.hasCustomDraftContent);
const stepsWithSourcedSettings = steps.filter((step) => step.hasSourcedSettings);
const publicReadyVerifiedSteps = steps.filter((step) => step.readiness === "ready_for_public_learner_ui");

const report = {
  generatedAt: new Date().toISOString(),
  source: {
    knowledgeBase: "src/data/reikiKnowledgeBase.js",
    stepSettings: "src/data/reikiStepSettings.js"
  },
  meta: reikiKnowledgeMeta,
  summary: {
    totalLevels: reikiLevels.length,
    totalSteps: steps.length,
    expectedTotalLevels: EXPECTED_TOTAL_LEVELS,
    expectedTotalSteps: EXPECTED_TOTAL_STEPS,
    stepsWithCustomDraftContent: stepsWithCustomDraftContent.length,
    stepsWithGeneratedDraftOnly: stepsWithGeneratedDraftOnly.length,
    stepsWithSourcedSettings: stepsWithSourcedSettings.length,
    stepsMissingSourcedSettings: missingSourcedSettings.length,
    publicReadyVerifiedSteps: publicReadyVerifiedSteps.length
  },
  levels: reikiLevels.map((level) => ({
    id: level.id,
    name: level.name,
    count: level.count,
    stepLabel: level.stepLabel,
    theme: level.theme
  })),
  missingSourcedSettings: missingSourcedSettings.map(({ id, title, levelId, number }) => ({ id, title, levelId, number })),
  generatedDraftOnly: stepsWithGeneratedDraftOnly.map(({ id, title, levelId, number }) => ({ id, title, levelId, number })),
  customDraftContent: stepsWithCustomDraftContent.map(({ id, title, levelId, number }) => ({ id, title, levelId, number })),
  steps
};

if (steps.length !== EXPECTED_TOTAL_STEPS) {
  errors.push(`Expected ${EXPECTED_TOTAL_STEPS} step records, found ${steps.length}.`);
}

if (errors.length > 0) {
  console.error("Reiki step materials audit failed:");
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}

await mkdir(docsDir, { recursive: true });
await writeFile(jsonReportPath, `${JSON.stringify(report, null, 2)}\n`);
await writeFile(mdReportPath, buildMarkdown(report));

console.log("Reiki step materials coverage generated.");
console.log(`- total steps: ${report.summary.totalSteps}`);
console.log(`- custom draft content: ${report.summary.stepsWithCustomDraftContent}`);
console.log(`- generated draft only: ${report.summary.stepsWithGeneratedDraftOnly}`);
console.log(`- sourced settings: ${report.summary.stepsWithSourcedSettings}`);
console.log(`- missing sourced settings: ${report.summary.stepsMissingSourcedSettings}`);
