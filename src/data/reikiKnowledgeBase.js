function stepId(levelId, stepNumber) {
  return `RY-L${String(levelId).padStart(2, "0")}-S${String(stepNumber).padStart(2, "0")}`;
}

function makeDraftContent(level, stepTitle, stepNumber) {
  const id = stepId(level.id, stepNumber);
  const customDraft = STEP_DRAFTS[id];

  if (customDraft) return customDraft;

  return {
    intro: `${level.stepLabel} ${stepNumber} раздела «${level.name}» раскрывает тему «${stepTitle}» как практический ключ к следующему уровню работы в системе Рейки Иггдрасиль. Это черновое описание задаёт понятную рамку для ученика и требует сверки с авторской методичкой.`,
    meaning: `Смысл ступени — познакомить ученика с направлением «${stepTitle}», показать его место в общем пути курса и перевести тему из абстрактной идеи в регулярную практику, наблюдение и личный опыт.`,
    opens: [
      `базовое понимание темы «${stepTitle}»`,
      "связь этой темы с личной практикой ученика",
      "новый слой внимания к энергии, состоянию и намерению",
      "переход от теории к аккуратному практическому применению"
    ],
    skills: [
      "настраиваться перед практикой и завершать её заземлением",
      "вести дневник ощущений, образов и результатов",
      "отличать устойчивый опыт от случайных впечатлений",
      "работать бережно, без перегрузки и без обещаний мгновенного результата"
    ],
    result: `Ученик получает первичную рабочую карту темы «${stepTitle}», понимает, что именно тренировать дальше, и может продолжать практику с более ясным фокусом.`
  };
}

function makeCourseStep(level, stepTitle, stepNumber) {
  const draftContent = makeDraftContent(level, stepTitle, stepNumber);

  return {
    id: stepId(level.id, stepNumber),
    levelId: level.id,
    number: stepNumber,
    label: level.stepLabel,
    title: stepTitle,
    status: "structure_verified_from_user_corrections",
    intro: draftContent.intro,
    meaning: draftContent.meaning,
    opens: draftContent.opens,
    skills: draftContent.skills,
    result: draftContent.result,
    contentStatus: "needs_review"
  };
}

